export const DICTS: Record<Lang, Record<string, string>> = { en, ur, ar, es, fr };

/* ───────────────────────── context + provider ───────────────────────── */

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Translate a key (English string) into the active language. */
  t: (key: string) => string;
  dir: "ltr" | "rtl";
  /** BCP-47 tag for date/number formatting. */
  locale: string;
}

const Ctx = createContext<I18nCtx>({
  lang: DEFAULT_LANG,
  setLang: () => {},
  t: (k) => k,
  dir: "ltr",
  locale: "en",
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(DEFAULT_LANG);

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && LANGS.some((l) => l.code === saved)) setLangState(saved);
    } catch { /* storage unavailable — keep default */ }
  }, []);

  useEffect(() => {
    const meta = LANGS.find((l) => l.code === lang)!;
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  }, [lang]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);

  const t = useCallback((key: string) => DICTS[lang][key] ?? key, [lang]);

  const value = useMemo<I18nCtx>(() => {
    const meta = LANGS.find((l) => l.code === lang)!;
    return { lang, setLang, t, dir: meta.dir, locale: meta.locale };
  }, [lang, setLang, t]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}

/**
 * Format a Date for the active language: useI18n().locale drives it, so
 * Arabic gets Arabic month names, Urdu gets Urdu digits/style, etc.
 */
export function useLocaleDate() {
  const { locale } = useI18n();
  const fmtTime = useCallback(
    (d: Date) => d.toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false }),
    [locale],
  );
  const fmtDate = useCallback(
    (d: Date) => d.toLocaleDateString(locale, { weekday: "long", year: "numeric", month: "long", day: "numeric" }),
    [locale],
  );
  const fmtFull = useCallback((d: Date) => d.toLocaleString(locale), [locale]);
  return { fmtTime, fmtDate, fmtFull };
}
