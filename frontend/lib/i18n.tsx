/**
 * I18N — internationalisation for the whole panel.
 *
 * DELIBERATELY ZERO-DEPENDENCY. No next-intl, no react-intl: the app runs on
 * offline servers with no route to package registries, so everything ships in
 * this one file. The dictionary keys ARE the English strings, so any string
 * without a translation (or from a page not yet swept) falls back to English
 * gracefully — `t("Dashboard")` just returns "Dashboard".
 *
 * LANGUAGES: en (default), ur, ar (RTL), es, fr.
 *
 * USAGE
 *   const { t, lang, setLang, dir, locale } = useI18n();
 *   <span>{t("Dashboard")}</span>
 *   <button onClick={() => setLang("ar")}>العربية</button>
 *
 * The provider sets <html lang dir> live and persists the choice in
 * localStorage, mirroring how currency is stored (jb_currency).
 */

