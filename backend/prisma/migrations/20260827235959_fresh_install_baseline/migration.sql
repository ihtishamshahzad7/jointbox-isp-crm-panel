-- =============================================================================
-- Fresh-install baseline: the tables, columns, types, indexes and foreign keys
-- that earlier versions created with `prisma db push` instead of a migration.
--
-- WHY THIS EXISTS. Until here the migration chain alone could not build a
-- database: 52 tables (PowerOutage, NasAssignment, extra_fee, StaticIp, …),
-- 111 columns of existing tables, 14 enum types (and 8 enum values), their
-- sequences, indexes and foreign keys were only ever created by `db push`,
-- which earlier installers ran. The migrations that
-- follow were written against such a database: on an EMPTY one
-- `prisma migrate deploy` stopped at 20260828000000 ("PowerOutage" does not
-- exist) — and further on at 20260829030000, whose foreign key names a table
-- "Package" that is really "packages" (it only ever passed because the key
-- already existed), 20260829050000 ("Isp"."currency") and 20261003130000
-- ("extra_fee").
--
-- WHAT IT DOES. Creates exactly those objects, in the form Prisma generates for
-- the current schema.prisma (`prisma migrate diff --from-empty
-- --to-schema-datamodel`), so the migrations after it run on a fresh database
-- the same way they ran on existing ones. Generated by comparing that DDL with
-- the database the migrations before this one produce.
--
-- SAFE ON EXISTING DATABASES (where every object already exists): purely
-- additive and idempotent — CREATE … IF NOT EXISTS, ADD VALUE IF NOT EXISTS,
-- and pg_temp.jbx_apply() which skips anything already present, skips tables
-- that are views here (radacct/radpostauth after radius-schema-apply.sh), and
-- never forces a constraint that existing rows violate (WARNING instead).
-- Nothing is dropped, renamed, retyped or rewritten. Requires PostgreSQL 12+
-- (enum values added inside the migration's transaction).
--
-- Not created here: anything a LATER migration creates itself (for example
-- "subscriber_traffic_sample", which 20260907000000 creates with a plain
-- CREATE TABLE and would otherwise fail on). The remaining differences from
-- schema.prisma are reconciled at the end of the chain by 20261013120000.
-- =============================================================================


-- Session-local helper (pg_temp: gone when the migration's session ends).
-- Runs one DDL statement only where it is meaningful and still missing:
--   * skipped when the table is not a plain table here (e.g. radacct after
--     scripts/radius-schema-apply.sh turned it into a view over radius.radacct);
--   * an object that already exists is left exactly as it is;
--   * a constraint the EXISTING data violates is not forced: a WARNING names it
--     and the deploy continues (fresh databases have no data, so this never
--     applies to a new install).
CREATE OR REPLACE FUNCTION pg_temp.jbx_apply(p_table text, p_sql text) RETURNS void
LANGUAGE plpgsql AS $jbx$
BEGIN
  IF p_table IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema() AND c.relname = p_table AND c.relkind IN ('r', 'p')) THEN
    RAISE NOTICE 'jointbox: skipped, % is not a table in this schema: %', p_table, left(p_sql, 140);
    RETURN;
  END IF;
  EXECUTE p_sql;
EXCEPTION
  WHEN duplicate_object OR duplicate_table OR duplicate_column THEN
    NULL; -- already present
  WHEN unique_violation OR foreign_key_violation OR not_null_violation OR check_violation THEN
    RAISE WARNING 'jointbox: not applied, existing rows conflict: % (%)', left(p_sql, 200), SQLERRM;
END
$jbx$;

-- A primary key only for a table that has none yet (a table that already
-- exists here already has its key; adding a second one is an error).
CREATE OR REPLACE FUNCTION pg_temp.jbx_add_pk(p_table text, p_sql text) RETURNS void
LANGUAGE plpgsql AS $jbx$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE n.nspname = current_schema() AND c.relname = p_table AND k.contype = 'p') THEN
    RETURN;
  END IF;
  PERFORM pg_temp.jbx_apply(p_table, p_sql);
END
$jbx$;

